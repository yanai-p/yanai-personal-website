import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const read = lang => JSON.parse(readFileSync(new URL(`../translations/${lang}.json`,import.meta.url),'utf8'));
const source=read('he');
const locales=Object.fromEntries(['en','th','hi','si','zh-CN','ro','uz'].map(lang=>[lang,read(lang)]));
assert.equal(new Set(source).size,source.length,'Duplicate source keys');
for(const [lang,values] of Object.entries(locales)) {
 assert.equal(values.length,source.length,`${lang}: missing entries`);
 values.forEach((value,i)=>{
  assert.equal(typeof value,'string');assert.ok(value.trim(),`${lang}:${i}: empty entry`);
  assert.ok(!/[\u0590-\u05ff]/.test(value),`${lang}:${i}: untranslated Hebrew`);
  assert.deepEqual(value.match(/\{\w+\}/g)||[],source[i].match(/\{\w+\}/g)||[],`${lang}:${i}: interpolation tokens`);
 });
}
writeFileSync(new URL('../dist/locales.js',import.meta.url),'/* Generated by npm run build:locales from translations/*.json. */\nwindow.YanaiLocales = '+JSON.stringify({source,locales})+';\n');
console.log(`${Object.keys(locales).length} complete catalogs, ${source.length} entries each.`);
